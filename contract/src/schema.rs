//! Generated model schemas plus cross-field constraints from the contract.
use crate::models::{Dashboard, Document};
use serde_json::{json, Value};
use std::sync::OnceLock;

pub const VERSION: &str = "1";
pub const RENDERERS: &[&str] = &["value", "echarts", "vela", "html", "vega_lite"];

/// Workspace identity text is fixed content and never a localization reference.
/// Other portable/device metadata remains validated by its owning layer.
pub fn workspace_metadata() -> Value {
    json!({
        "$schema":"https://json-schema.org/draft/2020-12/schema",
        "$id":"https://facetra.app/contracts/workspace/v1/metadata.schema.json",
        "$comment":"Generated by facetra-contract; run Tools/check-contract.sh --write. Do not edit.",
        "type":"object", "required":["title"],
        "properties":{
            "title":{"type":"string", "pattern":"\\S"},
            "description":{"type":["string","null"]}
        },
        "allOf":[{"not":{"required":["i18n"]}},{"not":{"required":["localizations"]}}]
    })
}

pub fn info() -> Value {
    json!({"version": VERSION, "compatibleVersions": ["1"], "chartVersionField": false,
        "dashboardVersions": [1], "renderers": RENDERERS,
        "validationLevels": ["structure", "workspace", "execution"]})
}
pub fn schema(kind: &str) -> Option<Value> {
    static COMMON: OnceLock<Value> = OnceLock::new();
    let mut common = COMMON.get_or_init(generate).clone();
    common["$id"] = json!(format!(
        "https://facetra.app/contracts/charting/v1/{kind}.schema.json"
    ));
    common.as_object_mut().unwrap().remove("oneOf");
    match kind {
        "chart" => common["$ref"] = json!("#/$defs/Document"),
        "dashboard" => common["$ref"] = json!("#/$defs/Dashboard"),
        "common" => {
            common["oneOf"] = json!([{"$ref":"#/$defs/Document"},{"$ref":"#/$defs/Dashboard"}])
        }
        _ => return None,
    }
    Some(common)
}
fn generate() -> Value {
    let mut chart = serde_json::to_value(schemars::schema_for!(Document)).unwrap();
    let mut dashboard = serde_json::to_value(schemars::schema_for!(Dashboard)).unwrap();
    let mut definitions = chart
        .as_object_mut()
        .unwrap()
        .remove("$defs")
        .unwrap()
        .as_object()
        .unwrap()
        .clone();
    definitions.extend(
        dashboard
            .as_object_mut()
            .unwrap()
            .remove("$defs")
            .unwrap()
            .as_object()
            .unwrap()
            .clone(),
    );
    chart.as_object_mut().unwrap().remove("$schema");
    dashboard.as_object_mut().unwrap().remove("$schema");
    definitions.insert("Document".into(), chart);
    definitions.insert("Dashboard".into(), dashboard);
    let mut schema = json!({"$schema":"https://json-schema.org/draft/2020-12/schema",
        "$comment":"Generated by facetra-contract; run Tools/check-contract.sh --write. Do not edit.",
        "x-facetra-contract": info(), "$defs": definitions});
    let defs = schema["$defs"].as_object_mut().unwrap();
    // IDs, static limits and discriminator constraints are shared with the
    // validators below. Relational constraints (references, cycles, binding
    // types, bounds relative to each other) belong to workspace validation.
    for (name, fields) in [
        ("Metadata", vec!["id"]),
        ("Parameter", vec!["name"]),
        ("Dataset", vec!["id"]),
        ("Input", vec!["id"]),
        ("Tab", vec!["id"]),
        ("Panel", vec!["id", "chart"]),
        ("ParameterReference", vec!["param"]),
    ] {
        for field in fields {
            defs.get_mut(name).unwrap()["properties"][field] =
                json!({"type":"string","pattern":"^[A-Za-z0-9_-]{1,80}$"});
        }
    }
    defs.get_mut("Metadata").unwrap()["properties"]["title"]["pattern"] = json!("\\S");
    defs.get_mut("MessageReference").unwrap()["properties"]["i18n"] =
        json!({"type":"string","pattern":"^[A-Za-z0-9_.-]{1,120}$"});
    let locale = json!({"type":"string","pattern":"^[A-Za-z]{2,8}(-[A-Za-z0-9]{1,8})*$"});
    let catalog = defs.get_mut("MessageCatalog").unwrap();
    catalog["properties"]["defaultLocale"] = locale.clone();
    catalog["properties"]["messages"]["propertyNames"] =
        json!({"pattern":"^[A-Za-z0-9_.-]{1,120}$"});
    catalog["properties"]["messages"]["additionalProperties"] = json!({"type":"object","minProperties":1,"propertyNames":locale,"additionalProperties":{"type":"string","pattern":"\\S"}});
    defs.get_mut("Document").unwrap()["properties"]["sources"]["maxProperties"] = json!(32);
    defs.get_mut("Document").unwrap()["properties"]["sources"]["propertyNames"] =
        json!({"pattern":"^[A-Za-z0-9_-]{1,80}$"});
    for variant in defs.get_mut("ConcreteSource").unwrap()["oneOf"]
        .as_array_mut()
        .unwrap()
    {
        variant["properties"]["depends_on"] = json!({"type":["array","null"],"maxItems":32,"uniqueItems":true,
            "items":{"type":"string","pattern":"^[A-Za-z0-9_-]{1,80}$"}});
    }
    defs.get_mut("Metadata").unwrap()["properties"]["tags"]["items"] = json!({"type":"string","minLength":1,"maxLength":64,"pattern":"^[^\\u0000-\\u001F\\u007F-\\u009F]*\\S[^\\u0000-\\u001F\\u007F-\\u009F]*$"});
    for (name, field, max) in [
        ("Pagination", "max_pages", 1000),
        ("ForEach", "max_items", 10_000),
        ("HttpLimits", "max_requests", 10_000),
        ("HttpLimits", "max_bytes", 104_857_600),
        ("HttpLimits", "max_rows", 100_000),
        ("HttpLimits", "timeout_ms", 300_000),
        ("HttpRetry", "max_attempts", 5),
    ] {
        defs.get_mut(name).unwrap()["properties"][field]["minimum"] = json!(1);
        defs.get_mut(name).unwrap()["properties"][field]["maximum"] = json!(max);
    }
    defs.get_mut("HttpRetry").unwrap()["properties"]["delay_ms"]["maximum"] = json!(10_000);
    for field in ["next", "records"] {
        defs.get_mut("Pagination").unwrap()["properties"][field]["maxLength"] = json!(4096);
    }
    defs.get_mut("Dataset").unwrap()["allOf"] = json!([
        {"if":{"required":["ref"],"properties":{"ref":{"type":"string"}}},"then":{"properties":{"sources":{"type":"null"},"sql":{"type":"null"}}},
            "else":{"required":["sources"],"properties":{"sources":{"type":"array","minItems":1,"maxItems":32},"with":{"type":"null"}}}},
        {"if":{"required":["sources"],"properties":{"sources":{"type":"array","minItems":2}}},"then":{"required":["sql"],"properties":{"sql":{"type":"string"}}}}
    ]);
    defs.get_mut("Parameter").unwrap()["properties"]["width"]["exclusiveMinimum"] = json!(0);
    defs.get_mut("Parameter").unwrap()["allOf"] = json!([
        {"if":{"properties":{"type":{"const":"date"}}},"then":{"properties":{"minimum":{"type":"null"},"maximum":{"type":"null"}}}}
    ]);
    defs.get_mut("Dashboard").unwrap()["properties"]["version"] = json!({"const":1});
    defs.get_mut("Dashboard").unwrap()["properties"]["kind"] = json!({"const":"Dashboard"});
    defs.get_mut("Dashboard").unwrap()["properties"]["tabs"]["minItems"] = json!(1);
    for (field, min, max) in [
        ("columns", 1, 12),
        ("row_height", 24, 120),
        ("gap", 0, 32),
        ("min_width", 320, 2400),
    ] {
        let p = &mut defs.get_mut("Grid").unwrap()["properties"][field];
        p["minimum"] = json!(min);
        p["maximum"] = json!(max);
    }
    defs.get_mut("Grid").unwrap()["properties"]["type"] = json!({"const":"grid"});
    defs.get_mut("Panel").unwrap()["properties"]["height"]["minimum"] = json!(160);
    defs.get_mut("Panel").unwrap()["properties"]["height"]["maximum"] = json!(600);
    for (field, max) in [("width", 12), ("row_span", 24)] {
        defs.get_mut("Panel").unwrap()["properties"][field] =
            json!({"type":["integer","null"],"minimum":1,"maximum":max});
    }
    defs.get_mut("Compact").unwrap()["properties"]["card_height"]["minimum"] = json!(160);
    defs.get_mut("Compact").unwrap()["properties"]["card_height"]["maximum"] = json!(600);
    let c = defs.get_mut("Chart").unwrap();
    c["allOf"] = json!([
        {"if":{"required":["renderer"],"properties":{"renderer":{"const":"value"}}},"then":{"required":["value"],"properties":{"value":{"type":"string","minLength":1}},"not":{"anyOf":[{"required":["option"]},{"required":["scripts"]}]}}},
        {"if":{"required":["renderer"],"properties":{"renderer":{"enum":["echarts","vela","html","vega_lite"]}}},"then":{"required":["option"],"properties":{"option":{"type":"object"}},"not":{"required":["value"]}}},
        {"if":{"required":["renderer"],"properties":{"renderer":{"enum":["vela","html","vega_lite"]}}},"then":{"not":{"required":["scripts"]}}},
        {"if":{"required":["renderer"],"properties":{"renderer":{"const":"html"}}},"then":{"properties":{"option":{"type":"object","required":["html"],"additionalProperties":false,"properties":{"html":{"type":"string","minLength":1},"css":{"type":"string"},"data":{"type":["object","array"]}}}}}}
    ]);
    schema
}

/// Editor model decoding allows incomplete provider/layout settings. Saving and
/// workspace validation always use the full contract schema. Both shapes are
/// derived from the same definitions; this never changes published validity.
pub fn model_schema(kind: &str) -> Option<Value> {
    let mut schema = schema(kind)?;
    fn strip(value: &mut Value) {
        match value {
            Value::Object(map) => {
                for key in [
                    "minimum",
                    "maximum",
                    "minItems",
                    "maxItems",
                    "minLength",
                    "maxLength",
                    "pattern",
                    "propertyNames",
                ] {
                    map.remove(key);
                }
                for (key, child) in map.iter_mut() {
                    if ["properties", "$defs", "patternProperties"].contains(&key.as_str()) {
                        if let Some(definitions) = child.as_object_mut() {
                            for definition in definitions.values_mut() {
                                strip(definition);
                            }
                        }
                    } else {
                        strip(child);
                    }
                }
            }
            Value::Array(array) => array.iter_mut().for_each(strip),
            _ => {}
        }
    }
    strip(&mut schema);
    let defs = schema["$defs"].as_object_mut()?;
    for name in ["Dataset", "Parameter"] {
        defs.get_mut(name)?.as_object_mut()?.remove("allOf");
    }
    defs.get_mut("Dashboard")?["properties"]["version"] = json!({"type":"integer"});
    defs.get_mut("Dashboard")?["properties"]["kind"] = json!({"type":"string"});
    let mut properties = defs["ReferenceSource"]["properties"].as_object()?.clone();
    for variant in defs["ConcreteSource"]["oneOf"].as_array()? {
        properties.extend(variant["properties"].as_object()?.clone());
    }
    properties.insert(
        "source".into(),
        json!({"type":["string","null"],"enum":["duckdb","http","database","sqlite",null]}),
    );
    properties.insert("ref".into(), json!({"type":["string","null"]}));
    defs.insert(
        "Source".into(),
        json!({"type":"object","properties":properties,"additionalProperties":false}),
    );
    Some(schema)
}
